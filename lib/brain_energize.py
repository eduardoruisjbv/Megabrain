def pulse(d, t):
    """Intensidade da energia a uma distância d da origem, no instante t."""
    e = 0.0
    for offset, amp in ((0.0, 1.0), (PULSE_LOOP / 2, 0.6)):
        r = (t * PULSE_SPEED + offset) % PULSE_LOOP
        e += amp * math.exp(-(((d - r) / PULSE_WIDTH) ** 2))
    return min(e, 1.0)


def jitter(x, y, k):
    """Ruído determinístico para a cintilação dos pontos (-0.5 a 0.5)."""
    h = (x * 374761393 + y * 668265263 + k * 2147483647) & 0xFFFFFFFF
    h = ((h ^ (h >> 13)) * 1274126177) & 0xFFFFFFFF
    return ((h >> 8) & 1023) / 1023 - 0.5


def prepare(stride):
    """Reduz o mapa pelo stride (se o terminal for pequeno) e calcula a origem."""
    dots = [[(-1 if ch == "." else int(ch)) for ch in row[::stride]]
            for row in GRID[::stride]]
    h, w = len(dots), len(dots[0])
    src = None
    for y in range(h - 1, -1, -1):           # base do tronco
        xs = [x for x in range(w) if dots[y][x] >= 0]
        if xs:
            src = (sum(xs) / len(xs), y)
            break
    sx, sy = src
    dist = [[math.hypot(x - sx, y - sy) / w for x in range(w)] for y in range(h)]
    return dots, dist


def frame(dots, dist, n):
    """Monta as linhas de texto do quadro número n."""
    h, w = len(dots), len(dots[0])
    t = n / FPS
    breath = 0.94 + 0.06 * math.sin(t * 2.2)
    lines = []
    for cy in range(0, h, 4):
        line = []
        for cx in range(0, w, 2):
            mask, inside = 0, False
            for dy in range(4):
                for dx in range(2):
                    y, x = cy + dy, cx + dx
                    if y >= h or x >= w or dots[y][x] < 0:
                        continue
                    inside = True
                    base = dots[y][x] / 9
                    e = pulse(dist[y][x], t)
                    if base < 0.4:           # trilha de circuito: acende com a energia
                        v = base * 0.25 + e * 0.95
                    else:                    # massa do cérebro
                        v = base * 0.75 + e * 0.5
                    v = v * breath + 0.10 * jitter(x, y, n // 2)
                    if v > (BAYER[y % 4][x % 4] + 0.5) / 16:
                        mask |= BIT[(dx, dy)]
            line.append(chr(0x2800 + mask) if inside else " ")
        lines.append("".join(line).rstrip())
    return lines


def energize(seconds=None, out=sys.stdout):
    """Toca a animação num bloco fixo. Sem terminal interativo, imprime um quadro."""
    term_cols, term_rows = shutil.get_terminal_size((80, 25))
    interactive = out.isatty()
    stride = 1
    while True:                              # aumenta o passo só se não couber
        dots, dist = prepare(stride)
        block_w, block_h = (len(dots[0]) + 1) // 2, (len(dots) + 3) // 4
        fits = block_w <= term_cols - 2 and block_h <= term_rows - 1
        if not interactive or fits or stride >= 4:
            break
        stride += 1
    pad = " " * max((term_cols - block_w) // 2, 0)

    if not out.isatty():
        out.write("\n".join(pad + line for line in frame(dots, dist, 0)) + "\n")
        out.flush()
        return

    out.write("\033[?25l")                   # esconde o cursor
    total = int(seconds * FPS) if seconds else None
    n = 0
    try:
        while total is None or n < total:
            if n:
                out.write(f"\033[{block_h}A")   # volta ao topo do bloco (sem rolar)
            for line in frame(dots, dist, n):
                out.write(f"\r\033[K{pad}{line}\n")
            out.flush()
            n += 1
            time.sleep(1 / FPS)
    except KeyboardInterrupt:
        pass
    finally:
        out.write("\033[0m\033[?25h")        # restaura cursor
        out.flush()


if __name__ == "__main__":
    secs = float(sys.argv[1]) if len(sys.argv) > 1 else None
    energize(secs)
